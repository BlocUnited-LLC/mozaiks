    """The contract must describe the onboarding.yaml step format so the generator can produce valid configs."""
    contract_text = _read_text(ONBOARDING / "contract.yaml")

    assert "selector" in contract_text, (
        "contract.yaml must document the 'selector' field in the step config format"
    )
    assert "step_id" in contract_text or "id:" in contract_text, (
        "contract.yaml must document step id fields"
    )
    assert "placement" in contract_text, (
        "contract.yaml must document placement options (bottom | top | left | right)"
    )
